#!/usr/bin/env python3
"""Turn a Supabase dump (schema.sql + data.sql) into plain Postgres SQL for the VPS.

Usage: python server/db/build_sql.py <dump_dir> <out_dir>
Writes <out_dir>/schema.sql, <out_dir>/data.sql and <out_dir>/counts.tsv (rows per public table).

Schema: drops Supabase-only parts (auth schema refs, RLS policies, grants to anon/authenticated,
OWNER TO, publications, vault / pg_stat_statements). Keeps every table, column, constraint, default,
index, function and the audit trigger. auth.jwt() ->> 'email' becomes the session setting
app.user_email, which the API sets per request (set_config(..., true) inside the transaction).
Data: only the public schema COPY blocks and sequence values, loaded with
session_replication_role = replica so the audit trigger and FK triggers do not fire during import.
"""
import re
import sys
from pathlib import Path

SKIP = [
    re.compile(r"^CREATE POLICY", re.I),
    re.compile(r"^(GRANT|REVOKE)\b", re.I),
    re.compile(r"^ALTER DEFAULT PRIVILEGES", re.I),
    re.compile(r"^ALTER PUBLICATION", re.I),
    re.compile(r"OWNER TO", re.I),
    re.compile(r"ENABLE ROW LEVEL SECURITY", re.I),
    re.compile(r"^CREATE EXTENSION .*(pg_stat_statements|supabase_vault|pg_graphql|pgsodium)", re.I),
    re.compile(r"^COMMENT ON (SCHEMA|EXTENSION)", re.I),
    re.compile(r"^CREATE SCHEMA", re.I),
    re.compile(r"^SET (transaction_timeout|default_table_access_method)", re.I),
    re.compile(r"^SELECT pg_catalog\.set_config\('search_path'", re.I),
]


def split_statements(sql: str):
    """Split on ; outside quotes, dollar quotes and comments."""
    out, buf, i, n = [], [], 0, len(sql)
    dollar = None
    while i < n:
        ch = sql[i]
        if dollar:
            if sql.startswith(dollar, i):
                buf.append(dollar)
                i += len(dollar)
                dollar = None
                continue
            buf.append(ch)
            i += 1
            continue
        if ch == "-" and sql.startswith("--", i):
            j = sql.find("\n", i)
            j = n if j == -1 else j
            i = j
            continue
        if ch == "'":
            j = i + 1
            while j < n:
                if sql[j] == "'" and (j + 1 >= n or sql[j + 1] != "'"):
                    break
                j += 2 if sql[j] == "'" else 1
            buf.append(sql[i:j + 1])
            i = j + 1
            continue
        if ch == "$":
            m = re.match(r"\$[A-Za-z_]*\$", sql[i:])
            if m:
                dollar = m.group(0)
                buf.append(dollar)
                i += len(dollar)
                continue
        if ch == ";":
            stmt = "".join(buf).strip()
            if stmt:
                out.append(stmt)
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail:
        out.append(tail)
    return out


def build_schema(src: str) -> str:
    kept = []
    for st in split_statements(src):
        if any(p.search(st) for p in SKIP):
            continue
        if st.startswith("\\"):
            continue
        kept.append(st)
    sql = ";\n\n".join(kept) + ";\n"
    sql = sql.replace(
        "COALESCE(auth.jwt() ->> 'email', current_user)",
        "COALESCE(NULLIF(current_setting('app.user_email', true), ''), current_user)",
    )
    sql = sql.replace("(auth.jwt() ->> 'email')", "NULLIF(current_setting('app.user_email', true), '')")
    if re.search(r"\bauth\.", sql):
        bad = [l for l in sql.splitlines() if re.search(r"\bauth\.", l)]
        raise SystemExit("auth.* still referenced:\n" + "\n".join(bad))
    head = (
        "-- Generated by server/db/build_sql.py from the Supabase dump. Plain Postgres 16.\n"
        "SET client_min_messages = warning;\n"
        "CREATE SCHEMA IF NOT EXISTS extensions;\n"
    )
    return head + sql


def build_data(src: str):
    lines = src.splitlines(keepends=True)
    out = ["SET session_replication_role = replica;\n", "SET client_encoding = 'UTF8';\n",
           "SET standard_conforming_strings = on;\n"]
    counts = {}
    i = 0
    while i < len(lines):
        ln = lines[i]
        m = re.match(r'^COPY "public"\."([a-z_0-9]+)"', ln)
        if m:
            table, rows = m.group(1), 0
            out.append(ln)
            i += 1
            while lines[i].rstrip("\r\n") != "\\.":
                out.append(lines[i])
                rows += 1
                i += 1
            out.append("\\.\n\n")
            counts[table] = rows
        elif ln.startswith("SELECT pg_catalog.setval('\"public\"."):
            out.append(ln)
        i += 1
    out.append("SET session_replication_role = origin;\n")
    return "".join(out), counts


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    dst.mkdir(parents=True, exist_ok=True)
    (dst / "schema.sql").write_text(build_schema((src / "schema.sql").read_text(encoding="utf-8")),
                                    encoding="utf-8", newline="\n")
    data, counts = build_data((src / "data.sql").read_text(encoding="utf-8"))
    (dst / "data.sql").write_text(data, encoding="utf-8", newline="\n")
    (dst / "counts.tsv").write_text("".join(f"{t}\t{c}\n" for t, c in sorted(counts.items())),
                                    encoding="utf-8", newline="\n")
    print(f"tables with data blocks: {len(counts)}, rows: {sum(counts.values())}")


if __name__ == "__main__":
    main()
